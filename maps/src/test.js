document.addEventListener('routeRendered', () => {
  const cl = document.getElementById('corruptedToggle');
  const savedCl = localStorage.getItem('corruptedVisible');
  const showCl = savedCl === null ? true : savedCl === 'true';
  cl.checked = showCl;
  document.getElementById('corruptedLayer').setAttribute('visibility', showCl ? 'visible' : 'hidden');

  const sl = document.getElementById('settlementsToggle');
  const savedSl = localStorage.getItem('settlementsVisible');
  const showSl = savedSl === null ? true : savedSl === 'true';
  sl.checked = showSl;
  document.getElementById('settlementsLayer').setAttribute('visibility', showSl ? 'visible' : 'hidden');

  const cb = document.getElementById('basecampToggle');
  if (!cb) return;

  const roll = Math.random();
  const chosenIsland = roll < 0.7 ? ISLAND_MAIN : roll < 0.9 ? ISLAND_WEST : ISLAND_SMALL;
  const settlements = [SETTLEMENT_A, SETTLEMENT_B, SETTLEMENT_C, SETTLEMENT_D];
  let bp;
  do {
    bp = randomPointInPolygon(chosenIsland);
  } while (settlements.some(s => pointInPolygon(bp.x, bp.y, s)));
  document.getElementById('basecampDot').setAttribute('cx', bp.x.toFixed(1));
  document.getElementById('basecampDot').setAttribute('cy', bp.y.toFixed(1));
  document.getElementById('basecampRing').setAttribute('cx', bp.x.toFixed(1));
  document.getElementById('basecampRing').setAttribute('cy', bp.y.toFixed(1));
  document.getElementById('basecampLabel').setAttribute('x', bp.x.toFixed(1));
  document.getElementById('basecampLabel').setAttribute('y', (bp.y - 30).toFixed(1));
  const savedCamp = localStorage.getItem('basecampAlpha');
  const showCamp = savedCamp === null ? true : savedCamp === 'true';
  cb.checked = showCamp;
  document.getElementById('boundaries').setAttribute('visibility', showCamp ? 'visible' : 'hidden');

  const st = document.getElementById('stationsToggle');
  const savedSt = localStorage.getItem('stationsVisible');
  const showSt = savedSt === null ? true : savedSt === 'true';
  st.checked = showSt;
  document.getElementById('stationsLayer').setAttribute('visibility', showSt ? 'visible' : 'hidden');

  const wt = document.getElementById('waystonesToggle');
  const savedWt = localStorage.getItem('waystonesVisible');
  const showWt = savedWt === null ? true : savedWt === 'true';
  wt.checked = showWt;
  document.getElementById('waystonesLayer').setAttribute('visibility', showWt ? 'visible' : 'hidden');
});
